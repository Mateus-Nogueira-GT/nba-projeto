const normalizar = (nome: string) =>
  nome.normalize('NFD').replace(/\p{Diacritic}/gu, '').toLowerCase().replace(/\./g, '').trim()

const POR_NOME = new Map(ID_NBA_POR_NOME.map(([nome, id]) => [normalizar(nome), id] as const))

export function fotoDeReserva(nome: string): string | null {
  const id = POR_NOME.get(normalizar(nome))
  return id === undefined ? null : `https://cdn.nba.com/headshots/nba/latest/260x190/${id}.png`
}
